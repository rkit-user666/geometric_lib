def area(a, b):
    """
    Принимает числа a и b (стороны прямоугольника).
    Возвращает площадь прямоугольника.

    Пример вызова: area(3, 4) -> 12
    """
    return a * b

def perimeter(a, b):
    """
    Принимает числа a и b (стороны прямоугольника).
    Возвращает периметр прямоугольника.

    Пример вызова: perimeter(3, 4) -> 14
    """
    return 2 * (a + b)