def area(a, h):
    """
    Принимает число a (основание) и h (высоту).
    Возвращает площадь треугольника.

    Пример вызова: area(3, 4) -> 6.0
    """
    return a * h / 2

def perimeter(a, b, c):
    """
    Принимает числа a, b, c (стороны треугольника).
    Возвращает периметр треугольника.

    Пример вызова: perimeter(3, 4, 5) -> 12
    """
    return a + b + c