def area(a):
    '''
    Возвращает площадь квадрата.

    Параметры:
        a (int/float): длина стороны квадрата.

    Возвращаемое значение:
        (int/float): площадь квадрата (сторона в квадрате).

    Пример вызова:
        >>> area(4)
        16
    '''
    return a * a


def perimeter(a):
    '''
    Возвращает периметр квадрата.

    Параметры:
        a (int/float): длина стороны квадрата.

    Возвращаемое значение:
        (int/float): периметр квадрата (сумма всех четырех сторон).

    Пример вызова:
        >>> perimeter(4)
        16
    '''
    return 4 * a