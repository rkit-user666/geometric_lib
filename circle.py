import math

def area(r):
    '''
    Возвращает площадь круга.

    Параметры:
        r (int/float): радиус круга.

    Возвращаемое значение:
        (float): площадь круга, вычисленная по формуле pi * r^2.

    Пример вызова:
        >>> area(5)
        78.53981633974483
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Возвращает длину окружности (периметр круга).

    Параметры:
        r (int/float): радиус круга.

    Возвращаемое значение:
        (float): длина окружности, вычисленная по формуле 2 * pi * r.

    Пример вызова:
        >>> perimeter(5)
        31.41592653589793
    '''
    return 2 * math.pi * r
